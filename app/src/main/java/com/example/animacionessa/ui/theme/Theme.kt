@Composable
fun AnimacionesSATheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit
) {
    val colors = if (darkTheme) DarkColors else LightColors
    val splash = if (darkTheme) DarkSplashColors else LightSplashColors
    CompositionLocalProvider(LocalSplashColors provides splash) {
        MaterialTheme(
            colorScheme = colors,
            typography = AppTypography,
            content = content
        )
    }
}